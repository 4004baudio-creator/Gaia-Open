const LOCAL_STORAGE_KEY = 'gaia_open_experiential_ontology_v1';

export const loadStoredExperientialOntology = (): ExperientialOntologyNode[] => {
  if (typeof window === 'undefined') return INITIAL_EXPERIENTIAL_ONTOLOGY;
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (!raw) return INITIAL_EXPERIENTIAL_ONTOLOGY;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
  } catch (err) {
    console.warn('Failed to load saved experiential ontology:', err);
  }
  return INITIAL_EXPERIENTIAL_ONTOLOGY;
};

export const saveStoredExperientialOntology = (data: ExperientialOntologyNode[]): void => {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(data));
  } catch (err) {
    console.warn('Failed to save experiential ontology:', err);
  }
};
